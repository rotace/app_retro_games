fn draw_glyph_at<R: RenderTarget>(
    target: &mut R,
    x: i32,
    y: i32,
    rows: &[u16; 16],
    color: u32,
    scale: i32,
) {
    let s = scale.max(1);
    for (row, bits) in rows.iter().enumerate() {
        for col in 0..GLYPH_SIZE {
            let bit = GLYPH_SIZE - 1 - col;
            if bits & (1 << bit) != 0 {
                fill_rect(target, x + col * s, y + row as i32 * s, s, s, color);
            }
        }
    }
}

pub(crate) fn jp_text_width(text: &str, scale: i32) -> i32 {
    let s = scale.max(1);
    text.chars().count() as i32 * (GLYPH_SIZE + 1) * s
}

pub(crate) fn draw_jp_text<R: RenderTarget>(
    target: &mut R,
    mut x: i32,
    y: i32,
    text: &str,
    color: u32,
    scale: i32,
) {
    let s = scale.max(1);
    for c in text.chars() {
        if let Some(g) = glyph(c) {
            draw_glyph_at(target, x, y, &g, color, s);
        }
        x += (GLYPH_SIZE + 1) * s;
    }
}

pub(crate) fn draw_jp_text_centered<R: RenderTarget>(
    target: &mut R,
    cx: i32,
    y: i32,
    text: &str,
    color: u32,
    scale: i32,
) {
    let tw = jp_text_width(text, scale);
    draw_jp_text(target, cx - tw / 2, y, text, color, scale);
}
